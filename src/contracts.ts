// Shape of the /init response's dynamic_variables object. Every field is a
// JSON primitive (or a JSON-encoded string for the ticket list) because the
// assistant interpolates them as strings.
export interface InitDynamicVariables {
  // True when /init completed all steps without an unrecoverable error.
  init_ok: boolean;
  // True when the backend is ready to accept a new ticket. False whenever a
  // hard dependency (Actor, KV) is unavailable, so the caller is never sent
  // into a ticket-intake branch that cannot succeed.
  can_create_ticket: boolean;
  // Number of tickets actually presented in tickets_json (<= PRESENTABLE_TICKETS_LIMIT).
  tickets_count: number;
  // JSON-encoded array of presentable tickets (id, reference, subject,
  // status, status_summary, updated_at). Kept as a string for safe transport.
  tickets_json: string;
  // Value of the technician_available feature flag read from KV.
  technician_available: boolean;
  // Greeting text spoken by the greeting Speak node. Personalized when
  // tickets exist, generic otherwise.
  greeting_text: string;
  // Opaque key tying this call's ticket creation to a single idempotent Actor
  // operation. Generated from the stable call context in step 6.
  operation_id: string;
}

// Fallback values used when /init fails or is unreachable. They are also the
