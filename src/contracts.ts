// Shared data contracts and validation helpers for the Telnyx developer
// support assistant.
//
// This module defines the pure, dependency-free shapes used across the Edge
// Function: the ticket model stored in the caller's Actor, the dynamic
// variables written by the /init webhook (and the subset the tool is allowed
// to write back), the request/response of the create-ticket webhook, the FAQ
// topic used by the MCP server, and a set of business limits.
//
// Keeping the contracts here lets every handler, the Actor implementation
// (step 5), the MCP server (step 7), and the deployment script share the same
// definitions, which avoids drift between the backend and the assistant.

// ---------------------------------------------------------------------------
// Business limits
// ---------------------------------------------------------------------------

// Maximum length of a ticket subject. Enforced in validateSubject.
export const MAX_SUBJECT_LENGTH = 100;

// Maximum length of a ticket description. Enforced in validateDescription.
export const MAX_DESCRIPTION_LENGTH = 1500;

// Word-count limits for an FAQ long answer. Range enforced when the FAQ
// catalogue is authored (see faq.ts in step 7).
export const MIN_FAQ_LONG_ANSWER_WORDS = 80;
export const MAX_FAQ_LONG_ANSWER_WORDS = 120;

// Maximum number of recent tickets presented verbally by the assistant on
// initialization. Older tickets remain in Actor storage but are not read out.
export const PRESENTABLE_TICKETS_LIMIT = 3;

// Tickets updated within this window (in days) are considered "recent" and
// may be presented, alongside all "open" tickets regardless of age.
export const RECENT_TICKET_WINDOW_DAYS = 30;

// Maximum length of an operation_id, used only as a sanity guard against
// abusive preset values. operation_id is generated from the call context
// and dedupes repeated webhook deliveries.
export const MAX_OPERATION_ID_LENGTH = 128;

// ---------------------------------------------------------------------------
// Ticket model (persisted in the caller's Actor)
// ---------------------------------------------------------------------------

// Lifecycle of a support ticket. A new ticket always starts as "open".
// "in_progress" indicates a technician has picked it up; "resolved" closes it.
export type TicketStatus = "open" | "in_progress" | "resolved";

// A single support ticket, stored in the caller's Actor state. Dates are
// ISO-8601 strings to remain JSON-serializable through Actor storage.
export interface Ticket {
  // UUIDv4 generated by the Actor on creation.
  id: string;
  // Short, human-readable reference, unique within this caller's tickets.
  // Generated by the Actor from next_ticket_number (e.g. "T-0007").
  reference: string;
  // Caller-provided subject, validated to <= MAX_SUBJECT_LENGTH characters.
  subject: string;
  // Caller-provided description, validated to <= MAX_DESCRIPTION_LENGTH.
  description: string;
  // Current lifecycle status.
  status: TicketStatus;
  // Short, voice-friendly summary of the current status, written by the
  // caller's Actor (e.g. "Awaiting handling."). Read aloud by the assistant.
  status_summary: string;
  // ISO-8601 creation timestamp.
  created_at: string;
  // ISO-8601 last-update timestamp.
  updated_at: string;
  // Deduplication key. Two create-ticket webhooks with the same operation_id
  // return the same ticket. Prevents retries from creating duplicates.
  operation_id: string;
}

// Persistent state of one caller's Actor. Stored under a single key in
// this.ctx.storage. The next_ticket_number counter guarantees unique
// references even when the ticket list grows.
export interface ActorState {
  // Next reference number assigned by createTicket. Monotonic.
  next_ticket_number: number;
  // All tickets for this caller, in insertion order. Historical fixtures may
  // have older dates; the init handler sorts and selects the voice subset.
  tickets: Ticket[];
}

// The status_summary assigned to a brand-new ticket.
export const NEW_TICKET_STATUS_SUMMARY = "Awaiting handling.";

// Business input for one actor creation. Caller identity is resolved by the
// Function before RPC; no phone number belongs in this actor input or state.
export interface CreateTicketInput {
  subject: string;
  description: string;
  operation_id: string;
}

// Minimal creation result. A repeated operation returns these same identifiers.
export type CreateTicketResult = Pick<Ticket, "id" | "reference">;

// Demo-only input. The actor assigns ids and references itself, while fixtures
// may supply documented statuses and historical timestamps for a voice demo.
// A stable operation_id identifies a fixture across repeated seed calls.
export interface DemoTicketInput extends CreateTicketInput {
  status: TicketStatus;
  status_summary: string;
  created_at: string;
  updated_at: string;
}

// Explicit batch wrapper used by the preparation-only actor method.
export interface SeedDemoTicketsInput {
  tickets: DemoTicketInput[];
}

// Number of new fixtures inserted; existing operation ids are left untouched.
export interface SeedDemoTicketsResult {
  added_count: number;
}

